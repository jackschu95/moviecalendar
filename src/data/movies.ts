// Generate dates dynamically - always shows movies for upcoming days
const today = new Date();
const getDaysFromNow = (days: number, hour: number = 19, minute: number = 30) => {
  const date = new Date(today);
  date.setDate(date.getDate() + days);
  date.setHours(hour, minute, 0, 0);
  return date;
};

